#!/usr/bin/env bash
#
# T106 — Scaffolds a new venue adapter.
#
#   make new-venue NAME=cboe
#   ./scripts/new-venue.sh cboe
#
# Generates:
#   apps/venue-adapter-<name>/build.gradle.kts
#   apps/venue-adapter-<name>/src/main/java/ch/swisstms/venue/<name>/<Name>VenueAdapter.java
#   apps/venue-adapter-<name>/src/main/resources/application.yml
#   apps/venue-adapter-<name>/src/test/java/ch/swisstms/venue/<name>/<Name>BasicLifecycleTest.java
#   docs/decisions/0xxx-venue-adapter-<name>.md  (numbered next available)
# and updates settings.gradle.kts.

set -euo pipefail

NAME="${1:-${NAME:-}}"
if [[ -z "${NAME}" ]]; then
  echo "Usage: $0 <name>   or   make new-venue NAME=<name>"
  exit 1
fi

LOWER="$(echo "${NAME}" | tr '[:upper:]' '[:lower:]')"
PASCAL="$(echo "${LOWER:0:1}" | tr '[:lower:]' '[:upper:]')${LOWER:1}"
DIR="apps/venue-adapter-${LOWER}"

if [[ -d "${DIR}" ]]; then
  echo "✗ ${DIR} already exists"
  exit 1
fi

echo "→ Scaffolding ${DIR} (class ${PASCAL}VenueAdapter)…"

mkdir -p "${DIR}/src/main/java/ch/swisstms/venue/${LOWER}"
mkdir -p "${DIR}/src/main/resources"
mkdir -p "${DIR}/src/test/java/ch/swisstms/venue/${LOWER}"
mkdir -p "${DIR}/helm"

cat > "${DIR}/build.gradle.kts" <<EOF
plugins {
    \`java-library\`
    id("org.springframework.boot") version "3.3.4"
    id("io.spring.dependency-management") version "1.1.6"
}

description = "Swiss-TMS — ${PASCAL} venue adapter."

dependencies {
    implementation("org.springframework.boot:spring-boot-starter")
    implementation("org.springframework.boot:spring-boot-starter-actuator")
    implementation(project(":libs:domain-model"))
    implementation(project(":libs:time-sync"))
    implementation(project(":libs:observability"))

    testImplementation("org.springframework.boot:spring-boot-starter-test")
    testImplementation("net.jqwik:jqwik:1.9.1")
    testRuntimeOnly("org.junit.platform:junit-platform-launcher:1.11.0")
}
EOF

cat > "${DIR}/src/main/java/ch/swisstms/venue/${LOWER}/${PASCAL}VenueAdapter.java" <<EOF
package ch.swisstms.venue.${LOWER};

import ch.swisstms.domain.execution.ExecutionReport;
import ch.swisstms.domain.health.HealthSnapshot;
import ch.swisstms.domain.health.LatencyTier;
import ch.swisstms.domain.marketdata.MarketDataTick;
import ch.swisstms.domain.marketdata.SubscriptionRequest;
import ch.swisstms.domain.order.CancelRequest;
import ch.swisstms.domain.order.Order;
import ch.swisstms.domain.order.OrderAck;
import ch.swisstms.domain.order.ReplaceRequest;
import ch.swisstms.domain.ports.VenueGatewayPort;
import ch.swisstms.time_sync.RegulatoryClock;

import org.springframework.stereotype.Component;

import java.util.concurrent.CompletableFuture;
import java.util.concurrent.CompletionStage;
import java.util.concurrent.Flow;
import java.util.concurrent.SubmissionPublisher;

/**
 * Generated by scripts/new-venue.sh — implements {@link VenueGatewayPort}
 * for ${PASCAL}.
 *
 * <p>Constitution Principle I — adding a new venue means adding a new
 * adapter alone. The OMS, EMS, reconciler, reporting and surveillance
 * services pick this up automatically via Spring DI (SpringVenueRouter).
 *
 * <p>TODO: replace TODOs below with the venue's protocol implementation.
 */
@Component
public class ${PASCAL}VenueAdapter implements VenueGatewayPort {

    private static final String VENUE_MIC = "TODO"; // 4-char MIC

    private final SubmissionPublisher<ExecutionReport> executions = new SubmissionPublisher<>();
    private final SubmissionPublisher<MarketDataTick> marketData = new SubmissionPublisher<>();

    @Override
    public CompletionStage<OrderAck> submitOrder(Order order) {
        // TODO: translate Order → venue protocol; await ack
        throw new UnsupportedOperationException("submitOrder not yet implemented");
    }

    @Override public CompletionStage<Void> cancelOrder(CancelRequest req) {
        throw new UnsupportedOperationException();
    }
    @Override public CompletionStage<Void> replaceOrder(ReplaceRequest req) {
        throw new UnsupportedOperationException();
    }
    @Override public Flow.Publisher<ExecutionReport> executions() { return executions; }
    @Override public Flow.Publisher<MarketDataTick> marketData(SubscriptionRequest req) { return marketData; }
