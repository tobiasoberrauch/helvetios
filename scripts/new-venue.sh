EOF

cat > "${DIR}/src/main/resources/application.yml" <<EOF
spring:
  application:
    name: venue-adapter-${LOWER}
server:
  port: 81??     # TODO: pick a free port
management:
  endpoints:
    web:
      exposure:
        include: health, metrics, prometheus
EOF

cat > "${DIR}/src/test/java/ch/swisstms/venue/${LOWER}/${PASCAL}BasicLifecycleTest.java" <<EOF
package ch.swisstms.venue.${LOWER};

import ch.swisstms.domain.health.HealthSnapshot;
import ch.swisstms.domain.health.LatencyTier;

import org.junit.jupiter.api.Test;

import static org.assertj.core.api.Assertions.assertThat;

/** TODO: implement conformance suite mirroring tests/conformance/six-sti/. */
class ${PASCAL}BasicLifecycleTest {

    @Test
    void portMetadataIsConsistent() {
        ${PASCAL}VenueAdapter adapter = new ${PASCAL}VenueAdapter();
        assertThat(adapter.venueMic()).isNotNull();
        assertThat(adapter.tier()).isIn(LatencyTier.HOT, LatencyTier.WARM, LatencyTier.COLD);

        HealthSnapshot snap = adapter.health();
        assertThat(snap.venueId()).isEqualTo(adapter.venueMic());
    }
}
EOF

# Find next free ADR number
ADR_DIR="docs/decisions"
NEXT=$(ls "${ADR_DIR}" 2>/dev/null | sed -nE 's/^([0-9]{4})-.*/\1/p' | sort -n | tail -1)
NEXT=$((10#${NEXT:-0} + 1))
ADR_NUM=$(printf '%04d' $NEXT)
ADR_FILE="${ADR_DIR}/${ADR_NUM}-venue-adapter-${LOWER}.md"

cat > "${ADR_FILE}" <<EOF
---
status: proposed
date: $(date -u +%Y-%m-%d)
deciders: TBD
---

# ADR ${ADR_NUM}: Onboard ${PASCAL} as a new venue adapter

## Context and Problem Statement

We need to connect to ${PASCAL}. As per Constitution Principle I, this is
an additive change — only the new adapter module is created; the domain,
OMS, EMS, reconciler, reporting and surveillance services stay
untouched.

## Decision

Implement ${DIR}/ as a new ${PASCAL}VenueAdapter implementing
\`VenueGatewayPort\`. Latency tier: \`WARM\` by default; revisit if the
venue exposes a co-location option.

## Implementation checklist

- [ ] MIC chosen (4 chars, ISO 10383)
- [ ] Protocol selected (FIX 4.4 / FIX 5.0 SP2 / proprietary binary / vendor SDK)
- [ ] Conformance test suite (mirror tests/conformance/six-sti/)
- [ ] Drop-copy stream wired to \`warm.dropcopy.${LOWER}.v1\` (Constitution V)
- [ ] Helm chart in ${DIR}/helm/
- [ ] Tilt extension in tools/tilt/extensions/venue_adapter_${LOWER}.star
- [ ] CODEOWNERS entry for ${DIR}/
EOF

# Add to settings.gradle.kts
SETTINGS="settings.gradle.kts"
if ! grep -q "apps:venue-adapter-${LOWER}" "${SETTINGS}"; then
  cat >> "${SETTINGS}" <<EOF

// Generated by scripts/new-venue.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
include("apps:venue-adapter-${LOWER}")
EOF
fi

echo "✓ Scaffolded ${DIR}"
echo "✓ Wrote ${ADR_FILE}"
echo "✓ Updated ${SETTINGS}"
echo ""
echo "Next steps:"
echo "  1. fill in the TODOs in ${PASCAL}VenueAdapter"
echo "  2. add a conformance test that exercises NEW → PARTIAL_FILL → FILL"
echo "  3. extend tools/tilt/extensions/ with a venue_adapter_${LOWER}.star"
